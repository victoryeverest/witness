def generate_yara_rule_from_strings(name: str, strings: list[str],
                                       condition: str = "any of them",
                                       description: str = "",
                                       attack_techniques: Optional[list[str]] = None) -> str:
    """Generate a YARA rule from a list of suspicious strings.
    """
    safe_name = name.replace(" ", "_").replace("-", "_")
    lines = [f"rule {safe_name} : witNESS_generated {{"]
    if description:
        lines.append("    // " + description)
    if attack_techniques:
        lines.append("    // techniques: " + ", ".join(attack_techniques))
    lines.append("    strings:")
    for i, s in enumerate(strings):
        # Escape quotes.
        escaped = s.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        $s{i} = "{escaped}" nocase')
    lines.append("    condition:")
    lines.append(f"        {condition}")
    lines.append("}")
    return "\n".join(lines) + "\n"


async def propose_yara_rule_from_evidence(session: AsyncSession,
                                            investigation_id: str,
                                            *,
                                            name: str,
                                            suspicious_strings: list[str],
                                            description: str = "",
                                            attack_techniques: Optional[list[str]] = None,
                                            ) -> DetectionRule:
    body = generate_yara_rule_from_strings(name, suspicious_strings,
                                              description=description,
                                              attack_techniques=attack_techniques)
    rule = DetectionRule(
        id=f"DR-YARA-{uuid.uuid4().hex[:8].upper()}",
        ruleType="yara",
        name=name,
        body=body,
        parsed={"strings": suspicious_strings},
        source=f"witness:agent:{investigation_id}",
        version="0.1",
        license_="internal",
        contentHash=sha256_text(body),
        attackTechniques=attack_techniques or [],
        validated=False,
        deployed=False,
    )
    session.add(rule)
    await session.flush()
    return rule


# --------------------------------------------------------------------------- #
# Validation — runs the rule through Sigma / YARA compilation
# --------------------------------------------------------------------------- #

async def validate_rule(rule: DetectionRule) -> tuple[bool, str]:
    """Validate a rule by compiling it. Returns (ok, error_message)."""
    if rule.ruleType == "sigma":
        try:
            from sigma.collection import SigmaCollection
            SigmaCollection.from_yaml(rule.body)
            return True, ""
        except Exception as e:
            return False, f"sigma_compile_failed:{e}"
    elif rule.ruleType == "yara":
        try:
            import yara
            yara.compile(source=rule.body)
            return True, ""
        except Exception as e:
            return False, f"yara_compile_failed:{e}"
    elif rule.ruleType == "behavioral":
        try:
            json.loads(rule.body)
            return True, ""
        except Exception as e:
            return False, f"behavioral_json_invalid:{e}"
    return False, f"unknown_rule_type:{rule.ruleType}"


async def validate_all_pending(session: AsyncSession) -> dict[str, int]:
    """Walk all un-validated DetectionRules, validate them, mark validated
    if they pass."""
    res = await session.execute(
        select(DetectionRule).where(DetectionRule.validated == False)
    )
    rules = list(res.scalars().all())
    summary = {"validated": 0, "failed": 0, "skipped": 0}
    for r in rules:
        ok, err = await validate_rule(r)
        if ok:
            r.validated = True
            summary["validated"] += 1
        else:
            log.warning(f"rule_validation_failed:{r.id} {err}")
            summary["failed"] += 1
    await session.flush()
    return summary
