"""WITNESS rule generation (§105).

Agents can propose Sigma / YARA / Suricata / detection-logic rules from
observed evidence. Per §105, every generated rule must be:
- syntax validated
- tested
- reviewed
- versioned

It must NOT be auto-deployed. Rules are persisted in `DetectionRule` rows
with `deployed=False` and require human review before going live.
"""
from __future__ import annotations

import json
import uuid
from typing import Any, Optional

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from ..models import DetectionRule
from ..core.evidence import list_evidence
from ..utils.crypto import sha256_text
from ..utils.logging import get_logger
from ..utils.time import utc_now


log = get_logger("witness.rulegen")


# --------------------------------------------------------------------------- #
# Sigma rule authoring (§105)
# --------------------------------------------------------------------------- #

def generate_sigma_rule_from_pattern(name: str, pattern: dict[str, Any],
                                       description: str = "",
                                       attack_techniques: Optional[list[str]] = None) -> str:
    """Generate a Sigma YAML rule body from a flat {field: value} pattern.

    The pattern is interpreted as a single selection with AND semantics.
    Each value can be a string, number, or list (OR semantics).
    """
    lines = [
        f"title: {name}",
        "status: experimental",
        f"description: {description or 'Auto-generated by WITNESS from observed evidence'}",
        f"date: {utc_now().date().isoformat()}",
    ]
    if attack_techniques:
        tags = [f"attack.{t.lower().replace('.', '_')}" for t in attack_techniques]
        lines.append("tags:")
        for t in tags:
            lines.append(f"    - {t}")
    lines.append("logsource:")
    lines.append("    product: windows")
    lines.append("    service: sysmon")
    lines.append("detection:")
    lines.append("    selection:")
    for k, v in pattern.items():
        # Sigma supports `|contains` and `|endswith` modifiers; default to plain eq.
        if isinstance(v, list):
            lines.append(f"        {k}:")
            for item in v:
                lines.append(f"            - {item}")
        else:
            lines.append(f"        {k}: {v}")
    lines.append("    condition: selection")
    lines.append("falsepositives:")
    lines.append("    - Unknown — review before deployment")
    lines.append("level: medium")
    return "\n".join(lines) + "\n"


async def propose_sigma_rule_from_evidence(session: AsyncSession,
                                              investigation_id: str,
                                              *,
                                              name: str,
                                              event_kind: str,
                                              matching_fields: list[str],
                                              description: str = "",
                                              attack_techniques: Optional[list[str]] = None,
                                              ) -> DetectionRule:
    """Inspect evidence for a given event_kind, derive a Sigma rule pattern
    from the matching_fields, and persist it as a DetectionRule with
    deployed=False (pending human review).
    """
    evs = await list_evidence(session, investigation_id)
    pattern: dict[str, Any] = {}
    for ev in evs:
        nd = ev.normalizedData or {}
        if nd.get("event_kind") != event_kind:
            continue
        for fld in matching_fields:
            v = nd.get(fld)
            if v is None:
                continue
            if fld not in pattern:
                pattern[fld] = v
            elif pattern[fld] != v and not isinstance(pattern[fld], list):
                pattern[fld] = [pattern[fld], v]
            elif isinstance(pattern[fld], list) and v not in pattern[fld]:
                pattern[fld].append(v)
    if not pattern:
        raise ValueError(f"no_evidence_for_event_kind:{event_kind}")
    body = generate_sigma_rule_from_pattern(name, pattern, description, attack_techniques)
    rule = DetectionRule(
        id=f"DR-SIG-{uuid.uuid4().hex[:8].upper()}",
        ruleType="sigma",
        name=name,
        body=body,
        parsed=pattern,
        source=f"witness:agent:{investigation_id}",
        version="0.1",
        license_="internal",
        contentHash=sha256_text(body),
        attackTechniques=attack_techniques or [],
        validated=False,  # pending validation
        deployed=False,   # pending human review
    )
    session.add(rule)
    await session.flush()
    return rule


